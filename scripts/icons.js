/* ── Met à jour le bouton thème selon l'état courant ────────────
   isDark = true  → on est en mode sombre  → affiche "☀ Clair"  (soleil)
   isDark = false → on est en mode clair   → affiche "🌙 Sombre" (lune)
   ─────────────────────────────────────────────────────────────── */
function _setBtnTheme(isDark) {
  const btn = document.getElementById('btnTheme');
  if (!btn) return;
  btn.innerHTML = isDark
    ? ICONS.sun  + ' <span class="btn-theme-lbl">Clair</span>'
    : ICONS.moon + ' <span class="btn-theme-lbl">Sombre</span>';
}

/* ── Initialisation au chargement (applique l'état sauvegardé) ── */
(function () {
  const saved = localStorage.getItem('gantt4cad_theme');
  _setBtnTheme(saved === 'dark');
})();
